import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');
const require = createRequire(import.meta.url);

/** Custom display labels that differ from title-cased kebab keys. */
const LABEL_OVERRIDES = {
    'wand-sparkles': 'AI writing',
};

function titleCaseKey(key) {
    return key
        .split('-')
        .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
        .join(' ');
}

function resolveDynamicImportsPath() {
    const packageJsonPath = require.resolve('lucide-react/package.json');
    return path.join(
        path.dirname(packageJsonPath),
        'dist',
        'esm',
        'dynamicIconImports.js',
    );
}

function extractIconKeys(source) {
    const keys = new Set();
    const pattern = /["']([a-z0-9-]+)["']\s*:/g;
    let match;

    while ((match = pattern.exec(source)) !== null) {
        keys.add(match[1]);
    }

    return [...keys].sort((a, b) => a.localeCompare(b));
}

async function main() {
    const importsPath = resolveDynamicImportsPath();
    const source = await readFile(importsPath, 'utf8');
    const keys = extractIconKeys(source);

    if (keys.length === 0) {
        throw new Error(
            `No icon keys found in ${importsPath}. Lucide layout may have changed.`,
        );
    }

    const options = keys.map((key) => {
        const label = LABEL_OVERRIDES[key] ?? titleCaseKey(key);
        const searchText = `${key} ${label}`.toLowerCase();

        return { key, label, searchText };
    });

    const outDir = path.join(root, 'resources', 'js', 'lib');
    const outFile = path.join(outDir, 'icon-catalog.ts');

    await mkdir(outDir, { recursive: true });

    const header = `/** Generated by scripts/generate-icon-catalog.mjs — do not edit manually. */\n`;
    const body = `export const ICON_OPTIONS = ${JSON.stringify(options, null, 4)} as const;\n\nexport type IconKey = (typeof ICON_OPTIONS)[number]['key'];\n\nexport type IconOption = (typeof ICON_OPTIONS)[number];\n\nexport const ICON_KEYS = new Set<string>(\n    ICON_OPTIONS.map((option) => option.key),\n);\n`;

    await writeFile(outFile, header + body, 'utf8');

    console.log(
        `Wrote ${options.length} icons to ${path.relative(root, outFile)}`,
    );
}

main().catch((error) => {
    console.error(error);
    process.exit(1);
});
